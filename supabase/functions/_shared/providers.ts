/* ICICI Bank merchant payment gateway (adapter — awaiting credentials) */
/* ------------------------------------------------------------------ */

export class IciciProvider implements PaymentProvider {
  readonly id = "icici" as const;

  private assertConfigured() {
    const missing = [
      "ICICI_MERCHANT_ID",
      "ICICI_API_KEY",
      "ICICI_API_SECRET",
      "ICICI_BASE_URL",
      "ICICI_WEBHOOK_SECRET",
    ].filter((key) => !Deno.env.get(key));
    if (missing.length) {
      throw new HttpError(
        "provider_not_configured",
        `ICICI merchant gateway is not configured (missing: ${missing.join(", ")}). ` +
          "Supply the merchant credentials and ICICI API specification, or set " +
          "NEXT_PUBLIC_PAYMENT_PROVIDER=razorpay.",
        503,
      );
    }
  }

  async createOrder(): Promise<ProviderOrder> {
    this.assertConfigured();
    // Implementation is intentionally gated: ICICI's merchant API contract
    // (endpoint paths, request signing scheme, order/hosted-checkout payload)
    // must come from the bank's onboarding pack. See docs/PAYMENT-PROVIDERS.md.
    throw new HttpError(
      "provider_not_implemented",
      "ICICI order creation will be enabled once the merchant API contract is supplied.",
      501,
    );
  }

  async verifyWebhook(): Promise<VerifiedEvent> {
    this.assertConfigured();
    throw new HttpError(
      "provider_not_implemented",
      "ICICI webhook verification will be enabled once the merchant API contract is supplied.",
      501,
    );
  }
}

/* ------------------------------------------------------------------ */

export function getProvider(id: ProviderId): PaymentProvider {
  return id === "icici" ? new IciciProvider() : new RazorpayProvider();
}

async function hmacSha256Hex(secret: string, message: string): Promise<string> {
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(message));
  return [...new Uint8Array(sig)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** Constant-time comparison to avoid signature timing leaks. */
function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}
