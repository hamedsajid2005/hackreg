import { HttpError, requiredEnv } from "./http.ts";

/**
 * Payment provider adapter.
 *
 * Razorpay is fully implemented (server-side order creation, dynamic UPI QR and
 * signed webhook verification). The ICICI Bank merchant gateway is implemented
 * behind the same interface but intentionally left inert until merchant
 * credentials and API documentation are supplied — see docs/PAYMENT-PROVIDERS.md.
 * No payment is ever simulated.
 */

export type ProviderId = "razorpay" | "icici";

export type ProviderOrder = {
  provider: ProviderId;
  orderId: string;
  amountPaise: number;
  currency: string;
  keyId?: string;
  hostedUrl?: string;
  qr: { id: string; imageUrl: string | null; expiresAt: string | null } | null;
  checkoutMode: "razorpay_checkout" | "hosted_redirect" | "qr_only";
};

export type VerifiedEvent = {
  kind: "success" | "failure" | "cancelled" | "expired" | "ignored";
  orderId: string | null;
  paymentId: string | null;
  amountPaise: number;
  currency: string;
  method: string | null;
  qrCodeId: string | null;
  gatewayStatus: string;
  raw: unknown;
};

export interface PaymentProvider {
  readonly id: ProviderId;
  createOrder(input: {
    amountPaise: number;
    currency: string;
    receipt: string;
    notes: Record<string, string>;
    description: string;
  }): Promise<ProviderOrder>;
  verifyWebhook(rawBody: string, headers: Headers): Promise<VerifiedEvent>;
  /**
   * Server-side read of payments captured against a dynamic UPI QR.
   * Used to reconcile when a webhook is delayed or the account does not emit
   * payment.captured for QR settlements. Optional: not every provider needs it.
   */
  reconcileQrPayments?(qrCodeId: string, fromUnix?: number): Promise<VerifiedEvent[]>;
}

