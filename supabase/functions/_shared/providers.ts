/* Razorpay                                                            */
/* ------------------------------------------------------------------ */

const RAZORPAY_API = "https://api.razorpay.com/v1";

function razorpayAuth(): string {
  const keyId = requiredEnv("RAZORPAY_KEY_ID");
  const keySecret = requiredEnv("RAZORPAY_KEY_SECRET");
  return `Basic ${btoa(`${keyId}:${keySecret}`)}`;
}

async function razorpayFetch(path: string, body: unknown): Promise<any> {
  const res = await fetch(`${RAZORPAY_API}${path}`, {
    method: "POST",
    headers: { Authorization: razorpayAuth(), "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const text = await res.text();
  let json: any = null;
  try {
    json = JSON.parse(text);
  } catch {
    json = null;
  }
  if (!res.ok) {
    // Never surface raw gateway payloads or credentials to the browser.
    console.error("[zelvation] razorpay error", res.status, json?.error?.description);
    throw new HttpError(
      "gateway_error",
      "The payment gateway rejected the request. Please try again in a moment.",
      502,
    );
  }
  return json;
}

export class RazorpayProvider implements PaymentProvider {
  readonly id = "razorpay" as const;

  async createOrder(input: {
    amountPaise: number;
    currency: string;
    receipt: string;
    notes: Record<string, string>;
    description: string;
  }): Promise<ProviderOrder> {
    const order = await razorpayFetch("/orders", {
      amount: input.amountPaise,
      currency: input.currency,
      receipt: input.receipt,
      notes: input.notes,
      payment_capture: 1,
    });

    let qr: ProviderOrder["qr"] = null;

    // Dynamic UPI QR — generated by the gateway for this exact order amount.
    // Only when the merchant account has UPI QR enabled.
    if ((Deno.env.get("RAZORPAY_ENABLE_UPI_QR") ?? "false") === "true") {
      try {
        const closeBy = Math.floor(Date.now() / 1000) + 15 * 60;
        const qrCode = await razorpayFetch("/payments/qr_codes", {
          type: "upi_qr",
          name: "ZELVATION registration",
          usage: "single_use",
          fixed_amount: true,
          payment_amount: input.amountPaise,
          currency: input.currency,
          description: input.description,
          close_by: closeBy,
          notes: input.notes,
        });
        qr = {
          id: qrCode.id,
          imageUrl: qrCode.image_url ?? null,
          expiresAt: qrCode.close_by ? new Date(qrCode.close_by * 1000).toISOString() : null,
        };
      } catch (err) {
        // A QR failure must not block the hosted checkout path.
        console.error("[zelvation] qr create failed", err instanceof Error ? err.message : err);
      }
    }

    return {
      provider: "razorpay",
      orderId: order.id,
      amountPaise: order.amount,
      currency: order.currency,
      keyId: requiredEnv("RAZORPAY_KEY_ID"),
      qr,
      checkoutMode: "razorpay_checkout",
    };
  }

  /**
   * GET /v1/payments/qr_codes/:id/payments
   * QR-code payments carry `order_id: null`, so this is the authoritative way to
   * find a captured payment for a QR that belongs to one of our orders.
   */
  async reconcileQrPayments(qrCodeId: string, fromUnix?: number): Promise<VerifiedEvent[]> {
    const params = new URLSearchParams({ count: "10" });
    if (fromUnix) params.set("from", String(Math.max(0, Math.floor(fromUnix) - 60)));
    try {
      const res = await fetch(
        `${RAZORPAY_API}/payments/qr_codes/${encodeURIComponent(qrCodeId)}/payments?${params}`,
        { headers: { Authorization: razorpayAuth() } },
      );
      if (!res.ok) {
        console.error("[zelvation] qr reconcile http", res.status);
        return [];
      }
      const body = await res.json();
      const items: any[] = Array.isArray(body?.items) ? body.items : [];
      return items.map((p) => ({
        kind: p.status === "captured" ? ("success" as const) : ("ignored" as const),
        orderId: p.order_id ?? null,
        paymentId: p.id ?? null,
        amountPaise: Number(p.amount ?? 0),
        currency: p.currency ?? "INR",
        method: p.method ?? "upi",
        qrCodeId,
        gatewayStatus: `qr.reconcile.${p.status ?? "unknown"}`,
        raw: p,
      }));
    } catch (err) {
      console.error("[zelvation] qr reconcile failed", err instanceof Error ? err.message : err);
      return [];
    }
  }

  async verifyWebhook(rawBody: string, headers: Headers): Promise<VerifiedEvent> {
    const secret = requiredEnv("RAZORPAY_WEBHOOK_SECRET");
    const signature = headers.get("x-razorpay-signature") ?? "";
    if (!signature) {
      throw new HttpError("invalid_signature", "Missing webhook signature.", 401);
    }

    const expected = await hmacSha256Hex(secret, rawBody);
    if (!timingSafeEqual(expected, signature)) {
      throw new HttpError("invalid_signature", "Webhook signature verification failed.", 401);
    }

    const payload = JSON.parse(rawBody);
    const event: string = payload.event ?? "";
    const payment = payload.payload?.payment?.entity;
    const qrEntity = payload.payload?.qr_code?.entity;
    const orderEntity = payload.payload?.order?.entity;

    const orderId: string | null =
      payment?.order_id ?? payment?.notes?.order_id ?? orderEntity?.id ?? null;
    const qrCodeId: string | null = payment?.qr_code_id ?? qrEntity?.id ?? null;

    if (event === "payment.captured" || event === "order.paid") {
      const amount = payment?.amount ?? orderEntity?.amount_paid ?? orderEntity?.amount ?? 0;
      return {
        kind: "success",
        orderId,
        paymentId: payment?.id ?? null,
        amountPaise: Number(amount),
        currency: payment?.currency ?? orderEntity?.currency ?? "INR",
        method: payment?.method ?? null,
        qrCodeId,
        gatewayStatus: event,
        raw: payload,
      };
    }

    if (event === "payment.failed") {
      return {
        kind: "failure",
        orderId,
        paymentId: payment?.id ?? null,
        amountPaise: Number(payment?.amount ?? 0),
        currency: payment?.currency ?? "INR",
        method: payment?.method ?? null,
        qrCodeId,
        gatewayStatus: event,
        raw: payload,
      };
    }

    if (event === "qr_code.credited") {
      // Money credited to a QR. We deliberately do NOT confirm on this event
      // alone: confirmation happens on payment.captured, matched via qr_code_id.
      return {
        kind: "ignored",
        orderId,
        paymentId: null,
        amountPaise: Number(qrEntity?.payment_amount ?? 0),
        currency: qrEntity?.currency ?? "INR",
        method: "upi_qr",
        qrCodeId,
        gatewayStatus: event,
        raw: payload,
      };
    }

    if (event === "qr_code.closed" || event === "qr_code.expired") {
      return {
        kind: "expired",
        orderId,
        paymentId: null,
        amountPaise: 0,
        currency: "INR",
        method: "upi_qr",
        qrCodeId,
        gatewayStatus: event,
        raw: payload,
      };
    }

    return {
      kind: "ignored",
      orderId,
      paymentId: payment?.id ?? null,
      amountPaise: Number(payment?.amount ?? 0),
      currency: "INR",
      method: null,
      qrCodeId,
      gatewayStatus: event || "unknown",
      raw: payload,
    };
  }
}

